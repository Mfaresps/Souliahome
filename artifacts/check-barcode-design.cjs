const puppeteer = require('puppeteer-core');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, userDataDir: path.resolve('artifacts/barcode-design-browser'), args: ['--no-first-run', '--disable-extensions'] });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.setViewport({ width: 1440, height: 1100, deviceScaleFactor: 1 });
    await page.goto('http://localhost:8080/design-preview/barcode-management-redesign.html', { waitUntil: 'networkidle0' });
    const count = () => page.$eval('#batch-total', e => Number(e.textContent));
    await page.click('[data-product="900011|25"]');
    await page.click('[data-product="900011|BL-01"]');
    assert.equal(await count(), 40);
    await page.screenshot({ path: 'artifacts/barcode-design-option-a.png', fullPage: true });
    await page.click('#open-preview');
    assert.equal(await page.$$eval('#preview-pages .label-paper', e => e.length), 40);
    await page.screenshot({ path: 'artifacts/barcode-design-label-preview.png' });
    await page.click('#preview-modal [data-close]');
    await page.click('[data-invoice="900010"]');
    assert.equal(await count(), 40);
    await page.click('[data-register="900010|37"]');
    await page.type('#count-reason', 'جرد فعلي للمعاينة');
    await page.click('#confirm-count');
    await page.click('#register-form [type="submit"]');
    assert.equal(await count(), 40);
    await page.click('[data-product="900010|37"]');
    assert.equal(await count(), 50);
    await page.$eval('[data-quantity="900010|37"]', e => { e.value = '5'; e.dispatchEvent(new Event('change', { bubbles: true })); });
    assert.equal(await count(), 45);
    await page.click('[data-option="gallery"]');
    assert.equal(await page.$$('.gallery-card').then(x => x.length), 6);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({ path: 'artifacts/barcode-design-option-b.png' });
    await page.click('#gallery-view [data-invoice="900009"]');
    assert.equal(await count(), 45);
    await page.click('[data-tab="registry"]');
    await page.click('#registry-view [data-units="900009|31"]');
    await page.click('#units-content [data-one-unit]');
    assert.equal(await page.$$eval('#preview-pages .label-paper', e => e.length), 1);
    await page.click('#preview-modal [data-close]');
    await page.click('[data-tab="receipts"]');
    await page.click('#clear-batch');
    await page.click('#back-to-gallery');
    await page.click('#gallery-view [data-invoice="900008"]');
    await page.click('[data-product="900008|BL-03"]');
    assert.equal(await count(), 100);
    await page.click('[data-option="workspace"]');
    await page.click('#reset-demo');
    await page.click('[data-product="900011|25"]');
    await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1 });
    await page.click('#mobile-preview');
    assert.equal(await page.$$eval('#preview-pages .label-paper', e => e.length), 20);
    await page.click('#preview-modal [data-close]');
    await page.evaluate(() => { document.getElementById('toast').hidden = true; scrollTo(0, 0); });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({ path: 'artifacts/barcode-design-mobile.png', fullPage: true });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    assert.equal(overflow, false, 'Mobile page should not overflow horizontally');
    assert.deepEqual(errors, []);
    console.log('PASS: selection, cross-invoice persistence, registration, quantity edits, both layouts, single-unit preview, 100-label cap, mobile overflow, no browser errors.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
